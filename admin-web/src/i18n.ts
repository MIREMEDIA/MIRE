export const lang = (typeof localStorage !== 'undefined' && localStorage.getItem('mire_lang') === 'en') ? 'en' : 'zh'
export function t(k: string, vars: Record<string, string | number> = {}): string {
  const s = msgs[lang][k] ?? msgs.zh[k] ?? k
  return s.replace(/\{(\w+)\}/g, (_, n) => (n in vars ? String(vars[n]) : `{${n}}`))
}
